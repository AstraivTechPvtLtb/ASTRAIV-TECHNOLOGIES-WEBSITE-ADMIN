export function SocialPlatformIcon({
  platform,
  className = 'h-4 w-4',
  ...props
}: {
  platform: string;
  className?: string;
} & React.SVGProps<SVGSVGElement>) {
  const p = (platform || '').toLowerCase().trim();

  switch (p) {
    case 'whatsapp':
      return <WhatsAppIcon className={className} {...props} />;
    case 'facebook':
      return <FacebookIcon className={className} {...props} />;
    case 'instagram':
      return <InstagramIcon className={className} {...props} />;
    case 'twitter':
    case 'x':
      return <TwitterIcon className={className} {...props} />;
    case 'linkedin':
      return <LinkedinIcon className={className} {...props} />;
    case 'github':
      return <GithubIcon className={className} {...props} />;
    case 'youtube':
      return <YoutubeIcon className={className} {...props} />;
    case 'discord':
      return <DiscordIcon className={className} {...props} />;
    case 'telegram':
      return <TelegramIcon className={className} {...props} />;
    case 'reddit':
      return <RedditIcon className={className} {...props} />;
    case 'threads':
      return <ThreadsIcon className={className} {...props} />;
    case 'tiktok':
      return <TiktokIcon className={className} {...props} />;
    case 'slack':
      return <SlackIcon className={className} {...props} />;
    case 'medium':
      return <MediumIcon className={className} {...props} />;
    default:
      return <GlobeIcon className={className} {...props} />;
  }
}
